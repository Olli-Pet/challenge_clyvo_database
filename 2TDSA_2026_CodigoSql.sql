-- PROCEDURE DE LOG
CREATE OR REPLACE PROCEDURE P_LOG_ERRO(
    P_NOME_PROCEDURE IN VARCHAR2,
    P_CODIGO_ERRO IN NUMBER,
    P_MSG_ERRO IN VARCHAR2
)
IS
    V_ID NUMBER;
BEGIN
    SELECT NVL(MAX(ID_LOG), 0) + 1 INTO V_ID FROM LOG_ERRO;

    INSERT INTO LOG_ERRO(
        ID_LOG, NOME_PROCEDURE, USUARIO_DB, DATA_ERRO, CODIGO_ERRO, MSG_ERRO
    )
    VALUES(
        V_ID, P_NOME_PROCEDURE, USER, SYSDATE, P_CODIGO_ERRO, P_MSG_ERRO
    );
END P_LOG_ERRO;
/

