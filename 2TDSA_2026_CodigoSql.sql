-- FUNCOES
CREATE OR REPLACE FUNCTION F_JSON_ATENDIMENTO(
    P_ID_PRONTUARIO NUMBER,
    P_PET VARCHAR2,
    P_RESPONSAVEL VARCHAR2,
    P_VETERINARIO VARCHAR2,
    P_PROCEDIMENTO VARCHAR2
)
RETURN VARCHAR2
IS
    V_ID NUMBER;
BEGIN
    SELECT ID_PRONTUARIO INTO V_ID
    FROM PRONTUARIO
    WHERE ID_PRONTUARIO = P_ID_PRONTUARIO;

    IF P_PET IS NULL OR P_RESPONSAVEL IS NULL OR P_VETERINARIO IS NULL THEN
        RAISE VALUE_ERROR;
    END IF;

    RETURN '{"id_prontuario":' || V_ID ||
           ',"pet":"' || P_PET ||
           '","responsavel":"' || P_RESPONSAVEL ||
           '","veterinario":"' || P_VETERINARIO ||
           '","procedimento":"' || P_PROCEDIMENTO || '"}';
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN '{"erro":"prontuario nao encontrado"}';
    WHEN VALUE_ERROR THEN
        RETURN '{"erro":"dados invalidos"}';
    WHEN OTHERS THEN
        RETURN '{"erro":"erro ao gerar JSON"}';
END F_JSON_ATENDIMENTO;
/

CREATE OR REPLACE FUNCTION F_FIM_TRATAMENTO(
    P_INICIO DATE,
    P_DURACAO NUMBER
)
RETURN DATE
IS
    V_DIAS NUMBER;
BEGIN
    IF P_INICIO IS NULL THEN
        RAISE VALUE_ERROR;
    END IF;

    IF P_DURACAO = 0 THEN
        RAISE ZERO_DIVIDE;
    END IF;

    IF P_DURACAO < 0 THEN
        RAISE VALUE_ERROR;
    END IF;

    V_DIAS := P_DURACAO;
    RETURN P_INICIO + V_DIAS;
EXCEPTION
    WHEN ZERO_DIVIDE THEN
        RETURN NULL;
    WHEN VALUE_ERROR THEN
        RETURN NULL;
    WHEN OTHERS THEN
        RETURN NULL;
END F_FIM_TRATAMENTO;
/

-- PROCEDURES RELATORIO
CREATE OR REPLACE PROCEDURE P_RELATORIO_JSON
IS
    V_QTD NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_QTD FROM PRONTUARIO;

    IF V_QTD = 0 THEN
        RAISE NO_DATA_FOUND;
    END IF;

    FOR R IN (
        SELECT PR.ID_PRONTUARIO,
               P.NOME PET,
               R.NOME RESPONSAVEL,
               V.NOME VETERINARIO,
               PR.PROCEDIMENTO
        FROM PRONTUARIO PR
        JOIN PET P ON PR.ID_PET = P.ID_PET
        JOIN RESPONSAVEL R ON P.ID_RESP = R.ID_RESP
        JOIN MED_VET V ON PR.ID_MED_VET = V.ID_MED_VET
        ORDER BY P.NOME
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(
            F_JSON_ATENDIMENTO(
                R.ID_PRONTUARIO,
                R.PET,
                R.RESPONSAVEL,
                R.VETERINARIO,
                R.PROCEDIMENTO
            )
        );
    END LOOP;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        P_LOG_ERRO('P_RELATORIO_JSON', SQLCODE, 'NENHUM PRONTUARIO ENCONTRADO');
    WHEN VALUE_ERROR THEN
        P_LOG_ERRO('P_RELATORIO_JSON', SQLCODE, 'ERRO DE VALOR');
    WHEN OTHERS THEN
        P_LOG_ERRO('P_RELATORIO_JSON', SQLCODE, SQLERRM);
END P_RELATORIO_JSON;
/

CREATE OR REPLACE PROCEDURE P_RELATORIO_TRATAMENTOS
IS
    CURSOR C_TRATAMENTOS IS
        SELECT ID_PET, STATUS, DURACAO_DIAS
        FROM TRATAMENTO
        ORDER BY ID_PET, STATUS;

    V_ID_PET NUMBER;
    V_STATUS VARCHAR2(20);
    V_DURACAO NUMBER;

    V_PET_ATUAL NUMBER := NULL;
    V_STATUS_ATUAL VARCHAR2(20) := NULL;
    V_TOTAL_STATUS NUMBER := 0;
    V_TOTAL_PET NUMBER := 0;
    V_TOTAL NUMBER := 0;
    V_EXISTE NUMBER := 0;
BEGIN
    OPEN C_TRATAMENTOS;

    LOOP
        FETCH C_TRATAMENTOS INTO V_ID_PET, V_STATUS, V_DURACAO;
        EXIT WHEN C_TRATAMENTOS%NOTFOUND;

        V_EXISTE := 1;

        IF V_PET_ATUAL IS NULL THEN
            V_PET_ATUAL := V_ID_PET;
            V_STATUS_ATUAL := V_STATUS;
        END IF;

        IF V_ID_PET <> V_PET_ATUAL THEN
            DBMS_OUTPUT.PUT_LINE(
                '  ' || V_PET_ATUAL || '  | ' || V_STATUS_ATUAL || ' | ' || V_TOTAL_STATUS
            );
            DBMS_OUTPUT.PUT_LINE(
                '  ' || V_PET_ATUAL || ' T| ' || '     ' || ' | ' || V_TOTAL_PET
            );

            V_PET_ATUAL := V_ID_PET;
            V_STATUS_ATUAL := V_STATUS;
            V_TOTAL_STATUS := 0;
            V_TOTAL_PET := 0;
        ELSIF V_STATUS <> V_STATUS_ATUAL THEN
            DBMS_OUTPUT.PUT_LINE(
                '  ' || V_PET_ATUAL || '  | ' || V_STATUS_ATUAL || ' | ' || V_TOTAL_STATUS
            );

            V_STATUS_ATUAL := V_STATUS;
            V_TOTAL_STATUS := 0;
        END IF;

        V_TOTAL_STATUS := V_TOTAL_STATUS + V_DURACAO;
        V_TOTAL_PET := V_TOTAL_PET + V_DURACAO;
        V_TOTAL := V_TOTAL + V_DURACAO;
    END LOOP;

    CLOSE C_TRATAMENTOS;

    IF V_EXISTE = 0 THEN
        RAISE NO_DATA_FOUND;
    END IF;

    DBMS_OUTPUT.PUT_LINE(
        '  ' || V_PET_ATUAL || '  | ' || V_STATUS_ATUAL || ' | ' || V_TOTAL_STATUS
    );
    DBMS_OUTPUT.PUT_LINE(
        '  ' || V_PET_ATUAL || ' T| ' || '     ' || ' | ' || V_TOTAL_PET
    );
    DBMS_OUTPUT.PUT_LINE(
        'Total| ' || '     ' || ' | ' || V_TOTAL
    );
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        IF C_TRATAMENTOS%ISOPEN THEN
            CLOSE C_TRATAMENTOS;
        END IF;
        P_LOG_ERRO('P_RELATORIO_TRATAMENTOS', SQLCODE, 'NENHUM TRATAMENTO ENCONTRADO');
    WHEN VALUE_ERROR THEN
        IF C_TRATAMENTOS%ISOPEN THEN
            CLOSE C_TRATAMENTOS;
        END IF;
        P_LOG_ERRO('P_RELATORIO_TRATAMENTOS', SQLCODE, 'ERRO DE VALOR');
    WHEN OTHERS THEN
        IF C_TRATAMENTOS%ISOPEN THEN
            CLOSE C_TRATAMENTOS;
        END IF;
        P_LOG_ERRO('P_RELATORIO_TRATAMENTOS', SQLCODE, SQLERRM);
END P_RELATORIO_TRATAMENTOS;
