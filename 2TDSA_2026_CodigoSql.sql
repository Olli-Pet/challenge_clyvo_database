-- TRIGGER
CREATE OR REPLACE TRIGGER TRG_AUDITORIA_PRONTUARIO
AFTER INSERT OR UPDATE OR DELETE ON PRONTUARIO
FOR EACH ROW
DECLARE
    V_ID NUMBER;
BEGIN
    SELECT NVL(MAX(ID_AUDITORIA), 0) + 1
    INTO V_ID
    FROM AUDITORIA_PRONTUARIO;

    IF INSERTING THEN
        INSERT INTO AUDITORIA_PRONTUARIO(
            ID_AUDITORIA, USUARIO_DB, OPERACAO, DATA_HORA,
            ID_PRONTUARIO_NOVO, ID_PET_NOVO, ID_MED_VET_NOVO, ID_CONSULTA_NOVO,
            PROCEDIMENTO_NOVO, DATA_PROCEDIMENTO_NOVO, LOCAL_NOVO
        )
        VALUES(
            V_ID, USER, 'INSERT', SYSDATE,
            :NEW.ID_PRONTUARIO, :NEW.ID_PET, :NEW.ID_MED_VET, :NEW.ID_CONSULTA,
            :NEW.PROCEDIMENTO, :NEW.DATA_PROCEDIMENTO, :NEW.LOCAL_ATENDIMENTO
        );
    ELSIF UPDATING THEN
        INSERT INTO AUDITORIA_PRONTUARIO(
            ID_AUDITORIA, USUARIO_DB, OPERACAO, DATA_HORA,
            ID_PRONTUARIO_ANTERIOR, ID_PET_ANTERIOR, ID_MED_VET_ANTERIOR, ID_CONSULTA_ANTERIOR,
            PROCEDIMENTO_ANTERIOR, DATA_PROCEDIMENTO_ANTERIOR, LOCAL_ANTERIOR,
            ID_PRONTUARIO_NOVO, ID_PET_NOVO, ID_MED_VET_NOVO, ID_CONSULTA_NOVO,
            PROCEDIMENTO_NOVO, DATA_PROCEDIMENTO_NOVO, LOCAL_NOVO
        )
        VALUES(
            V_ID, USER, 'UPDATE', SYSDATE,
            :OLD.ID_PRONTUARIO, :OLD.ID_PET, :OLD.ID_MED_VET, :OLD.ID_CONSULTA,
            :OLD.PROCEDIMENTO, :OLD.DATA_PROCEDIMENTO, :OLD.LOCAL_ATENDIMENTO,
            :NEW.ID_PRONTUARIO, :NEW.ID_PET, :NEW.ID_MED_VET, :NEW.ID_CONSULTA,
            :NEW.PROCEDIMENTO, :NEW.DATA_PROCEDIMENTO, :NEW.LOCAL_ATENDIMENTO
        );
    ELSE
        INSERT INTO AUDITORIA_PRONTUARIO(
            ID_AUDITORIA, USUARIO_DB, OPERACAO, DATA_HORA,
            ID_PRONTUARIO_ANTERIOR, ID_PET_ANTERIOR, ID_MED_VET_ANTERIOR, ID_CONSULTA_ANTERIOR,
            PROCEDIMENTO_ANTERIOR, DATA_PROCEDIMENTO_ANTERIOR, LOCAL_ANTERIOR
        )
        VALUES(
            V_ID, USER, 'DELETE', SYSDATE,
            :OLD.ID_PRONTUARIO, :OLD.ID_PET, :OLD.ID_MED_VET, :OLD.ID_CONSULTA,
            :OLD.PROCEDIMENTO, :OLD.DATA_PROCEDIMENTO, :OLD.LOCAL_ATENDIMENTO
        );
    END IF;
END;
