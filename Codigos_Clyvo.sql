SET SERVEROUTPUT ON
SET VERIFY OFF

-- DROPS
DROP TABLE PRONTUARIO CASCADE CONSTRAINTS;
DROP TABLE PET CASCADE CONSTRAINTS;
DROP TABLE VETERINARIO CASCADE CONSTRAINTS;
DROP TABLE RESPONSAVEL CASCADE CONSTRAINTS;
DROP TABLE LOG_ERRO CASCADE CONSTRAINTS;

-- TABELAS
CREATE TABLE LOG_ERRO(
    ID_LOG NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NOME_PROCEDURE VARCHAR2(100),
    USUARIO_DB VARCHAR2(100),
    DATA_ERRO DATE,
    CODIGO_ERRO NUMBER,
    MSG_ERRO VARCHAR2(4000)
);

CREATE TABLE RESPONSAVEL(
    ID_RESP NUMBER PRIMARY KEY,
    NOME VARCHAR2(100) NOT NULL,
    DATA_NASC DATE,
    CPF VARCHAR2(14) UNIQUE,
    EMAIL VARCHAR2(100)
);

CREATE TABLE VETERINARIO(
    ID_VETERINARIO NUMBER PRIMARY KEY,
    NOME VARCHAR2(100) NOT NULL,
    CRMV VARCHAR2(20) UNIQUE,
    EMAIL VARCHAR2(100)
);

CREATE TABLE PET(
    ID_PET NUMBER PRIMARY KEY,
    NOME VARCHAR2(100),
    DESCRICAO VARCHAR2(200),
    RACA VARCHAR2(100),
    DATA_NASC DATE,
    ID_RESP NUMBER NOT NULL,
    CONSTRAINT FK_RESP FOREIGN KEY(ID_RESP) REFERENCES RESPONSAVEL(ID_RESP)
);

CREATE TABLE PRONTUARIO(
    ID_PRONTUARIO NUMBER PRIMARY KEY,
    ID_PET NUMBER NOT NULL,
    PROCEDIMENTO VARCHAR2(200),
    DATA_PROCEDIMENTO DATE,
    LOCAL_ATENDIMENTO VARCHAR2(100),
    ID_VETERINARIO NUMBER NOT NULL,
    CONSTRAINT FK_PET FOREIGN KEY(ID_PET) REFERENCES PET(ID_PET),
    CONSTRAINT FK_VET FOREIGN KEY(ID_VETERINARIO) REFERENCES VETERINARIO(ID_VETERINARIO)
);

-- PROCEDURES

CREATE OR REPLACE PROCEDURE P_LOG_ERRO(
    P_NOME_PROC VARCHAR2,
    P_COD NUMBER,
    P_MSG VARCHAR2
)
IS
BEGIN
    INSERT INTO LOG_ERRO
    (NOME_PROCEDURE, USUARIO_DB, DATA_ERRO, CODIGO_ERRO, MSG_ERRO)
    VALUES (P_NOME_PROC, USER, SYSDATE, P_COD, P_MSG);
END;

CREATE OR REPLACE PROCEDURE P_INS_RESP(
    P_ID NUMBER,
    P_NOME VARCHAR2,
    P_DATA DATE,
    P_CPF VARCHAR2,
    P_EMAIL VARCHAR2
)
IS
BEGIN
    INSERT INTO RESPONSAVEL VALUES(P_ID, P_NOME, P_DATA, P_CPF, P_EMAIL);
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        P_LOG_ERRO('P_INS_RESP', SQLCODE, 'CPF DUPLICADO');
    WHEN VALUE_ERROR THEN
        P_LOG_ERRO('P_INS_RESP', SQLCODE, 'ERRO DE VALOR');
    WHEN OTHERS THEN
        P_LOG_ERRO('P_INS_RESP', SQLCODE, SQLERRM);
END;

CREATE OR REPLACE PROCEDURE P_INS_VET(
    P_ID NUMBER,
    P_NOME VARCHAR2,
    P_CRMV VARCHAR2,
    P_EMAIL VARCHAR2
)
