EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        P_LOG_ERRO('P_INS_VET', SQLCODE, 'CRMV DUPLICADO');
    WHEN VALUE_ERROR THEN
        P_LOG_ERRO('P_INS_VET', SQLCODE, 'ERRO DE VALOR');
    WHEN OTHERS THEN
        P_LOG_ERRO('P_INS_VET', SQLCODE, SQLERRM);
END;

CREATE OR REPLACE PROCEDURE P_INS_PET(
    P_ID NUMBER,
    P_NOME VARCHAR2,
    P_DESC VARCHAR2,
    P_RACA VARCHAR2,
    P_DATA DATE,
    P_RESP NUMBER
)
IS
BEGIN
    INSERT INTO PET VALUES(P_ID, P_NOME, P_DESC, P_RACA, P_DATA, P_RESP);
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        P_LOG_ERRO('P_INS_PET', SQLCODE, 'PET DUPLICADO');
    WHEN VALUE_ERROR THEN
        P_LOG_ERRO('P_INS_PET', SQLCODE, 'ERRO DE VALOR');
    WHEN OTHERS THEN
        P_LOG_ERRO('P_INS_PET', SQLCODE, SQLERRM);
END;

CREATE OR REPLACE PROCEDURE P_INS_PRONTUARIO(
    P_ID NUMBER,
    P_IDPET NUMBER,
    P_PROC VARCHAR2,
    P_DATA DATE,
    P_LOCAL VARCHAR2,
