-- JOINS COM GROUP BY
BEGIN
    FOR R IN (
        SELECT V.NOME, COUNT(PR.ID_PET) TOTAL
        FROM VETERINARIO V
        JOIN PRONTUARIO PR ON V.ID_VETERINARIO = PR.ID_VETERINARIO
        GROUP BY V.NOME
        ORDER BY TOTAL DESC
    ) LOOP
        DBMS_OUTPUT.PUT_LINE('MEDICO: '||R.NOME||' TOTAL: '||R.TOTAL);
    END LOOP;
END;

BEGIN
    FOR R IN (
        SELECT R.NOME, COUNT(P.ID_PET) TOTAL
        FROM RESPONSAVEL R
        JOIN PET P ON R.ID_RESP = P.ID_RESP
        GROUP BY R.NOME
        ORDER BY TOTAL DESC
    ) LOOP
        DBMS_OUTPUT.PUT_LINE('RESP: '||R.NOME||' PETS: '||R.TOTAL);
    END LOOP;
END;

BEGIN
    FOR R IN (
        SELECT P.NOME PET, V.NOME MEDICO, PR.PROCEDIMENTO
        FROM PRONTUARIO PR
        JOIN PET P ON PR.ID_PET = P.ID_PET
        JOIN VETERINARIO V ON PR.ID_VETERINARIO = V.ID_VETERINARIO
        ORDER BY P.NOME
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(R.PET||' - '||R.MEDICO||' - '||R.PROCEDIMENTO);
    END LOOP;
END;

-- LAG/LEAD
SELECT
    ID_PET,
    NVL(LAG(NOME) OVER(ORDER BY ID_PET),'VAZIO') ANTERIOR,
    NOME ATUAL,
    NVL(LEAD(NOME) OVER(ORDER BY ID_PET),'VAZIO') PROXIMO
FROM PET;

-- CURSORES
DECLARE
    CURSOR C_PETS IS SELECT NOME, RACA FROM PET;
    V_NOME PET.NOME%TYPE;
    V_RACA PET.RACA%TYPE;
BEGIN
    OPEN C_PETS;
    LOOP
        FETCH C_PETS INTO V_NOME, V_RACA;
        EXIT WHEN C_PETS%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('PET: '||V_NOME||' | '||V_RACA);
    END LOOP;
    CLOSE C_PETS;
END;

DECLARE
    CURSOR C_MED IS SELECT NOME FROM VETERINARIO;
    V_NOME VARCHAR2(100);
BEGIN
    OPEN C_MED;
    LOOP
        FETCH C_MED INTO V_NOME;
        EXIT WHEN C_MED%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('MEDICO: '||V_NOME);
    END LOOP;
    CLOSE C_MED;
END;

DECLARE
    CURSOR C_PRONT IS SELECT PROCEDIMENTO FROM PRONTUARIO;
    V_PROC VARCHAR2(100);
BEGIN
    OPEN C_PRONT;
    LOOP
        FETCH C_PRONT INTO V_PROC;
        EXIT WHEN C_PRONT%NOTFOUND;
        IF V_PROC = 'Vacina' THEN
            DBMS_OUTPUT.PUT_LINE('PREVENTIVO');
        ELSE
            DBMS_OUTPUT.PUT_LINE('OUTRO');
        END IF;
    END LOOP;
    CLOSE C_PRONT;
END;

-- RELATÓRIO FINAL
DECLARE
    CURSOR C_SUM IS
        SELECT V.NOME, COUNT(*) TOTAL
        FROM PRONTUARIO PR
        JOIN VETERINARIO V ON PR.ID_VETERINARIO = V.ID_VETERINARIO
        GROUP BY V.NOME;

    V_NOME VARCHAR2(100);
    V_TOTAL NUMBER;
BEGIN
    OPEN C_SUM;
    LOOP
        FETCH C_SUM INTO V_NOME, V_TOTAL;
        EXIT WHEN C_SUM%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('MEDICO: '||V_NOME||' TOTAL ATEND: '||V_TOTAL);
    END LOOP;
    CLOSE C_SUM;
END;

